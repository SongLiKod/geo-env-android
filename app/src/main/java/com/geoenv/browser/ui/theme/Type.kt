/* =====================================================================================
 * 状态色映射（环境 / 代理状态可视化）
 * ===================================================================================*/
private val statusColorMap = staticCompositionLocalOf { mapOf<String, androidx.compose.ui.graphics.Color>() }

@Composable
@ReadOnlyComposable
fun statusColor(status: String): androidx.compose.ui.graphics.Color =
    when (status) {
        "RUNNING", "OK", "ACTIVE" -> GeoEnvSemantic.Running
        "STARTING", "PENDING" -> GeoEnvSemantic.Starting
        "ERROR", "FAIL", "FROZEN" -> GeoEnvSemantic.Failed
        else -> GeoEnvSemantic.Stopped
    }

